# 教学目的：先追踪语句造成的状态变化，再区分显示结果、返回值和异常。
# 总体思路：七段代码彼此独立；第 1 小题只捕获预期异常，保证整份材料能够从头运行。
# 常见错误：把 append 的返回值当成列表，把两个名字误认为两个独立列表。

# %% R08-E01-P01
# 任务：解释给元组的第一个元素重新赋值会发生什么。
# 思路：元组不支持元素赋值；原语句会抛出 TypeError，而不是输出一个新元组。
# 易错点：捕获异常是演示保护，不是原题中赋值语句可以成功执行的意思。
# 创建包含三个整数的元组，保留原题变量名 T。
T = (1, 2, 3)
# 开始捕获预期错误，使后面的练习仍能运行。
try:
    # 尝试修改第 0 个位置；元组不可变，因此这一行抛出 TypeError。
    T[0] = 3
# 只处理原题预期出现的元组赋值类型错误。
except TypeError as error:
    # 输出异常名称和原因，便于学生把错误与普通输出区分开。
    print("TypeError:", error)

# %% R08-E01-P02
# 任务：区分 append 对列表的修改与 append 的返回值。
# 思路：整个 [4, 5] 被当作一个元素追加，append 本身返回 None，所以 print 输出 None。
# 易错点：列表变为 [1, 2, 3, [4, 5]]，但原题并没有打印这个变化后的列表。
# 每个小题重新建立自己的列表，避免依赖上一小题。
L = [1, 2, 3]
# 追加一个列表对象，再打印 append 的返回值 None。
print(L.append([4, 5]))

# %% R08-E01-P03
# 任务：追踪 sort 之后列表的排列顺序。
# 思路：sort 原地修改 L；随后打印 L，所以结果是 [1, 2, 3, 4]。
# 易错点：不要写 L = L.sort()，因为 sort 的返回值也是 None。
# 建立原题给出的无序整数列表。
L = [4, 2, 1, 3]
# 原地按升序排列列表中的整数。
L.sort()
# 输出排序后的列表 [1, 2, 3, 4]。
print(L)

# %% R08-E01-P04
# 任务：解释 extend 接收列表与字符串时分别追加什么。
# 思路：extend 逐项读取参数；字符串 fg 被逐字符读取为 f 和 g。
# 易错点：extend('fg') 不会把整个字符串 fg 作为一个新元素。
# 建立最初含 a、b、c 的列表。
L = ['a', 'b', 'c']
# 将参数列表中的 d、e 分别加入 L。
L.extend(['d', 'e'])
# 将字符串中的 f、g 分别加入 L。
L.extend('fg')
# 输出七个单字符字符串组成的列表。
print(L)

# %% R08-E01-P05
# 任务：读取两个列表推导式，一个转换数据，一个按条件筛选数据。
# 思路：第一个对每个单词取长度；第二个只保留长度严格大于 4 的原单词。
# 易错点：L2 的表达式是 x，因此返回的是单词，不是长度。
# 保存原题四个单词，顺序保持不变。
L = ["apple", "cat", "banana", "dog"]
# 对每个单词计算长度，依次得到 5、3、6、3。
L1 = [len(x) for x in L]
# 只留下长度大于 4 的 apple 与 banana。
L2 = [x for x in L if len(x) > 4]
# 显示长度列表 [5, 3, 6, 3]。
print(L1)
# 显示筛选出的单词列表 ['apple', 'banana']。
print(L2)

# %% R08-E01-P06
# 任务：预测一边遍历、一边删除同一列表时的真实结果。
# 思路：删掉 1 后 3 左移并被跳过；再删 5 后 7 左移并被跳过；最后删掉 9。
# 易错点：原题不是安全删除写法；最终剩下 [3, 7]，不是空列表。
# 建立五个奇数组成的原列表。
t = [1, 3, 5, 7, 9]
# 直接遍历正在被修改的 t，迭代位置仍继续向前移动。
for i in t:
    # 奇数除以 2 的余数为 1，在条件位置被视为真。
    if i % 2:
        # 删除当前访问到的数，后面元素随即左移。
        t.remove(i)
# 循环结束后输出 [3, 7]；这行在循环体外。
print(t)

# %% R08-E01-P07
# 任务：追踪函数参数、返回值与两个名字共享同一列表的关系。
# 思路：myappend 返回原列表本身，因此 x 与 y 指向同一个对象。
# 易错点：赋值给 y 没有复制列表；通过 y 追加 4 后，x 看到的也是四个元素。
# 定义函数，参数 L 接收调用者传入的列表引用。
def myappend(L):
    # 在同一个列表对象后追加整数 3。
    L.append(3)
    # 返回该列表对象，而不是创建一个副本。
    return L

# 创建最初的列表并让 x 引用它。
x = [1, 2]
# 函数追加 3 后返回同一个列表，y 与 x 因而共享对象。
y = myappend(x)
# 通过 y 修改共享列表，在末尾追加 4。
y.append(4)
# 通过 x 打印同一对象，结果是 [1, 2, 3, 4]。
print(x)
