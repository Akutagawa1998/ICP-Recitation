# 第 3 题：随机彩票号码，练习列表构建和独立的输出循环。
# 教学目的：区分生成数据的循环与显示已有数据的循环。
# 总体思路：固定种子只方便课堂复现；七个位置都独立使用 0 到 9 的随机整数。
# 常见错误：误以为数字必须互不相同，或把列表转成整数导致开头的 0 丢失。

# %% R08-E03
# 任务：生成并存储七个随机数字，再使用另一轮循环显示它们。
# 思路：先 append 七次，再逐个打印；用 end='' 将七个位置连成一行。
# 易错点：允许重复数字，也允许第一个数字是 0；不能强行生成 1000000 到 9999999 的整数。
# 导入标准库随机模块，不需要额外安装依赖。
import random

# 固定种子 8，使本节课每次演示得到相同的七个数字。
random.seed(8)
# 建立保存七个数字位置的空列表。
lottery_digits = []
# 生成循环执行七次，每次填入一个位置。
for position in range(7):
    # randint 的两个端点都包含在内，因此 0 和 9 都可能出现。
    digit = random.randint(0, 9)
    # 将本次数字作为单独的列表元素追加。
    lottery_digits.append(digit)
# 开始输出标签，并保持后续数字显示在同一行。
print("Lottery number: ", end="")
# 使用与生成循环分开的第二个循环显示列表中的所有数字。
for digit in lottery_digits:
    # 连续显示一个位置，不增加空格或换行。
    print(digit, end="")
# 七位号码显示完成后换行；固定种子下号码为 3562301。
print()
