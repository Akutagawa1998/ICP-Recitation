# 第 5 题：大于 n 的数字，练习参数、遍历和严格比较。
# 教学目的：把筛选条件写进可重复调用的函数，并按题目要求直接显示匹配值。
# 总体思路：逐项比较，只有 number > n 为真时才打印该元素。
# 常见错误：写成 >= 会错误包含与 n 相等的元素；只返回列表不能代替题目要求的显示。

# %% R08-E05
# 任务：接收数字列表和 n 两个参数，显示所有严格大于 n 的元素。
# 思路：保留原列表顺序，不改变传入数据，也不将重复值自动去重。
# 易错点：样例中两个 10 都不应输出；没有匹配值或空列表时不输出数字。
# 定义两个参数的函数；第一个参数保存待检查的数字列表。
def display_larger_than(numbers, n):
    # 逐个取出列表中的数字。
    for number in numbers:
        # 只接受严格大于阈值 n 的数字，不包括相等的情况。
        if number > n:
            # 按遇到的顺序显示匹配的数字。
            print(number)

# 传入含小于、等于、大于阈值的数据，预期只显示 15 与 23。
display_larger_than([4, 10, 15, 10, 23, -2], 10)
# 所有数字都不大于 10，因此这一调用不增加任何输出。
display_larger_than([4, 10, -2], 10)
# 空列表没有可遍历的元素，因此这一调用也没有输出。
display_larger_than([], 10)
